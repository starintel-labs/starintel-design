#!/usr/bin/env node
/**
 * build-css.mjs -- assemble the single-file theme from the granular sources.
 *
 *   node scripts/build-css.mjs          # regenerate theme.css
 *   node scripts/build-css.mjs --check  # exit 1 when theme.css is stale
 *
 * theme.css is committed so `import "@starintel/design/theme.css"` works with
 * zero build steps. The test suite verifies it never drifts from the parts.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const parts = ["tokens.css", "base.css", "layout.css", "components.css", "org.css", "motion.css"];

const header = `/*
 * @starintel/design -- obsidian-gold theme (default).
 * Generated by scripts/build-css.mjs from src/css/*. Do not edit by hand.
 * Granular sources: @starintel/design/css/{tokens,base,layout,components,org,motion}.css
 */

`;

const check = process.argv.includes("--check");
const bundle = header + parts.map((p) => readFileSync(join(root, "src", "css", p), "utf8").trimEnd()).join("\n\n") + "\n";

const target = join(root, "theme.css");
if (check) {
  const current = readFileSync(target, "utf8");
  if (current !== bundle) {
    console.error("theme.css is stale; run: node scripts/build-css.mjs");
    process.exit(1);
  }
  console.log("theme.css in sync with src/css parts");
} else {
  writeFileSync(target, bundle);
  console.log(`wrote theme.css (${bundle.length} bytes)`);
}
