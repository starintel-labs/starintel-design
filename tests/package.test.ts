/**
 * Package hygiene tests: exports resolve, theme bundle is in sync,
 * and every referenced asset exists.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

test("package name and exports contract", () => {
  assert.equal(pkg.name, "@starintel/design");
  assert.ok(pkg.exports["./theme.css"], "theme.css export missing");
  assert.ok(pkg.exports["."], "root export missing");
});

test("all export targets exist on disk", () => {
  for (const [key, value] of Object.entries<string>(pkg.exports)) {
    const target = join(root, value.replaceAll("*", "starintel-mark.svg").split("*")[0]!);
    assert.ok(existsSync(target), `export ${key} -> ${value} does not exist`);
  }
});

test("committed theme.css matches the generated bundle", () => {
  // Recompute the bundle the build script would produce and compare.
  const parts = ["tokens.css", "base.css", "layout.css", "components.css", "org.css", "motion.css"];
  const header = `/*
 * @starintel/design -- obsidian-gold theme (default).
 * Generated by scripts/build-css.mjs from src/css/*. Do not edit by hand.
 * Granular sources: @starintel/design/css/{tokens,base,layout,components,org,motion}.css
 */

`;
  const bundle =
    header + parts.map((p) => readFileSync(join(root, "src", "css", p), "utf8").trimEnd()).join("\n\n") + "\n";
  const committed = readFileSync(join(root, "theme.css"), "utf8");
  assert.equal(committed, bundle, "theme.css is stale; run: node scripts/build-css.mjs");
});

test("required identity assets exist", () => {
  for (const asset of [
    "starintel-mark.svg",
    "lambda-mark.svg",
    "lambda-network.svg",
    "lambda-grid.svg",
    "node-field.svg",
    "graph-grid.svg",
    "relation-path.svg",
  ]) {
    assert.ok(existsSync(join(root, "assets", asset)), `missing asset: ${asset}`);
  }
});

test("assets are svg and use the obsidian-gold palette", () => {
  const network = readFileSync(join(root, "assets", "lambda-network.svg"), "utf8");
  assert.match(network, /#e0b04a/, "gold accent missing from lambda-network");
  assert.match(network, /#090807/, "obsidian canvas missing from lambda-network");
});

test("agent design guide exists and names the package + theme", () => {
  const guide = readFileSync(join(root, "docs", "AGENT-DESIGN-GUIDE.md"), "utf8");
  assert.match(guide, /@starintel\/design/);
  assert.match(guide, /obsidian-gold/);
});
